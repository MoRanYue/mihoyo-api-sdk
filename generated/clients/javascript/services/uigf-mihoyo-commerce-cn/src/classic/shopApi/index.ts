import { MihoyoCommerceCNContext } from "../../api/mihoyoCommerceCNContext.js";
import {
  checkOrder,
  createOrder,
  getCurrencyAndCountryByIp,
  fetchGoods,
} from "../../api/shopApi/operations.js";
import {
  ShopApiCheckOrderOptionalParams,
  ShopApiCreateOrderOptionalParams,
  ShopApiGetCurrencyAndCountryByIpOptionalParams,
  ShopApiFetchGoodsOptionalParams,
} from "../../api/shopApi/options.js";
import { ShopGoodsRequest, CreateOrderRequest } from "../../models/uigf/mihoyo/commerce/models.js";
import {
  ApiResponseShopGoods,
  ApiResponseCurrencyAndCountry,
  ApiResponseJsonObject,
  ApiResponseOrderStatus,
} from "../../models/uigf/mihoyo/models.js";

/** Interface representing a ShopApi operations. */
export interface ShopApiOperations {
  checkOrder: (
    gameBiz: string,
    orderNo: string,
    game: string,
    region: string,
    uid: string,
    options?: ShopApiCheckOrderOptionalParams,
  ) => Promise<ApiResponseOrderStatus>;
  /** Sends a vendor-signed order request; no payment signing is generated by this SDK. */
  createOrder: (
    gameBiz: string,
    cookie: string,
    deviceId: string,
    body: CreateOrderRequest,
    options?: ShopApiCreateOrderOptionalParams,
  ) => Promise<ApiResponseJsonObject>;
  /** Returns the storefront currency and country. */
  getCurrencyAndCountryByIp: (
    gameBiz: string,
    options?: ShopApiGetCurrencyAndCountryByIpOptionalParams,
  ) => Promise<ApiResponseCurrencyAndCountry>;
  /** Returns purchasable catalogue entries for the authenticated game account. */
  fetchGoods: (
    gameBiz: string,
    body: ShopGoodsRequest,
    options?: ShopApiFetchGoodsOptionalParams,
  ) => Promise<ApiResponseShopGoods>;
}

function _getShopApi(context: MihoyoCommerceCNContext) {
  return {
    checkOrder: (
      gameBiz: string,
      orderNo: string,
      game: string,
      region: string,
      uid: string,
      options?: ShopApiCheckOrderOptionalParams,
    ) => checkOrder(context, gameBiz, orderNo, game, region, uid, options),
    createOrder: (
      gameBiz: string,
      cookie: string,
      deviceId: string,
      body: CreateOrderRequest,
      options?: ShopApiCreateOrderOptionalParams,
    ) => createOrder(context, gameBiz, cookie, deviceId, body, options),
    getCurrencyAndCountryByIp: (
      gameBiz: string,
      options?: ShopApiGetCurrencyAndCountryByIpOptionalParams,
    ) => getCurrencyAndCountryByIp(context, gameBiz, options),
    fetchGoods: (
      gameBiz: string,
      body: ShopGoodsRequest,
      options?: ShopApiFetchGoodsOptionalParams,
    ) => fetchGoods(context, gameBiz, body, options),
  };
}

export function _getShopApiOperations(context: MihoyoCommerceCNContext): ShopApiOperations {
  return {
    ..._getShopApi(context),
  };
}
